/**
 * SIMULATED delivery tracking for the three legs ReLoop cares about (see {@link DeliveryType}).
 *
 * <p><b>Nothing here is real tracking.</b> Locations come from {@link DemoLocations}; positions come from
 * {@link DeliverySimulator}; the only thing that moves a parcel is the demo "advance" call. Every response carries
 * {@code simulated: true} and {@link #SIMULATION_NOTICE}.</p>
 *
 * <p><b>Who can do what</b> (anything else on someone else's delivery is a 404):</p>
 * <ul>
 *   <li>STORE_TO_CUSTOMER — booked by the order's seller once order-service reports the order CONFIRMED (paid).</li>
 *   <li>CUSTOMER_TO_REPAIRER — booked by the customer or the repairer once the repairer has ACCEPTED a request
 *       whose delivery method is SEND_ITEM or PICKUP_DROPOFF.</li>
 *   <li>REPAIRER_TO_CUSTOMER — booked by the repairer once the repair is COMPLETED, or after QUOTE_REJECTED /
 *       CANCELLED if the item had been delivered to the workshop.</li>
 *   <li>Both parties see identical tracking data and either may press the demo advance.</li>
 * </ul>
 */
@Service
public class DeliveryTrackingService {

    public static final String SIMULATION_NOTICE = "SIMULATED DEMO TRACKING: locations are predefined Gujarat demo "
            + "points and the position is generated by ReLoop's simulator. No GPS device or courier service is involved.";
    public static final String CARRIER = "ReLoop Demo Courier (simulated)";

    private static final Logger log = LoggerFactory.getLogger(DeliveryTrackingService.class);
    private static final List<String> STATUS_FLOW = Arrays.stream(DeliveryStatus.values()).map(Enum::name).toList();
    private static final Set<RepairStatus> RETURN_AFTER_INBOUND = Set.of(RepairStatus.QUOTE_REJECTED, RepairStatus.CANCELLED);

    private final DeliveryRepository deliveries;
    private final DeliveryLocationPointRepository points;
    private final RepairRequestRepository requests;
    private final OrderServiceClient orderService;
    private final DeliverySimulator simulator;
    private final TrackingNumberGenerator trackingNumbers;

    public DeliveryTrackingService(DeliveryRepository deliveries, DeliveryLocationPointRepository points,
                                   RepairRequestRepository requests, OrderServiceClient orderService,
                                   DeliverySimulator simulator, TrackingNumberGenerator trackingNumbers) {
        this.deliveries = deliveries;
        this.points = points;
        this.requests = requests;
        this.orderService = orderService;
        this.simulator = simulator;
        this.trackingNumbers = trackingNumbers;
    }

    /* ───────────────────────────── demo locations ───────────────────────────── */

    public List<DemoLocationResponse> demoLocations() {
        return DemoLocations.ALL.stream().map(DemoLocationResponse::of).toList();
    }

    /* ───────────────────────────── booking ───────────────────────────── */

    @Transactional
    public DeliveryResponse book(AuthenticatedAccount caller, CreateDeliveryRequest request) {
        Map<String, String> errors = new LinkedHashMap<>();
        DeliveryType type = request.deliveryType();
        if (type.isRepairLeg()) {
            if (request.repairRequestId() == null) {
                errors.put("repairRequestId", "is required for " + type);
            }
            if (request.orderId() != null) {
                errors.put("orderId", "must be empty for " + type);
            }
        } else {
            if (request.orderId() == null) {
                errors.put("orderId", "is required for " + type);
            }
            if (request.repairRequestId() != null) {
                errors.put("repairRequestId", "must be empty for " + type);
            }
        }
        Optional<DemoLocation> origin = location("originCode", request.originCode(), errors);
        Optional<DemoLocation> destination = location("destinationCode", request.destinationCode(), errors);
        if (!errors.isEmpty()) {
            throw new RequestValidationException(errors);
        }

        Delivery d = new Delivery();
        d.setDeliveryType(type);
        d.setBookedByAccountId(caller.accountId());
        if (type == DeliveryType.STORE_TO_CUSTOMER) {
            bookStoreLeg(caller, request, d);
        } else {
            RepairRequest repair = visibleRepair(caller, request.repairRequestId());
            RepairerProfile workshop = repair.getRepairerProfile();
            if (type == DeliveryType.CUSTOMER_TO_REPAIRER) {
                checkInbound(repair);
                destination = destination.or(() -> workshopLocation(workshop));
            } else {
                checkReturn(caller, repair);
                origin = origin.or(() -> workshopLocation(workshop));
                if (destination.isEmpty()) {
                    destination = deliveries.findByRepairRequest_IdAndDeliveryType(repair.getId(), DeliveryType.CUSTOMER_TO_REPAIRER)
                            .flatMap(inbound -> DemoLocations.find(inbound.getOriginCode()));
                }
            }
            d.setRepairRequest(repair);
            d.setReferenceNumber(repair.getRequestNumber());
            d.setCustomerAccountId(repair.getCustomerAccountId());
            d.setPartnerAccountId(workshop.getAccountExternalId());
        }

        if (origin.isEmpty()) {
            errors.put("originCode", "is required for " + type + " (pick one from GET /api/tracking/demo-locations)");
        }
        if (destination.isEmpty()) {
            errors.put("destinationCode", "is required for " + type + " (pick one from GET /api/tracking/demo-locations)");
        }
        if (origin.isPresent() && destination.isPresent() && origin.get().equals(destination.get())) {
            errors.put("destinationCode", "must be a different demo location than the origin");
        }
        if (!errors.isEmpty()) {
            throw new RequestValidationException(errors);
        }
        setEnds(d, origin.get(), destination.get());

        d.setTrackingNumber(uniqueTrackingNumber());
        LocalDateTime now = LocalDateTime.now();
        DeliveryLocationPoint first = simulator.start(d, now, caller.accountId());
        deliveries.saveAndFlush(d);
        points.save(first);
        log.info("Simulated {} delivery {} booked by account {} ({} -> {})", type, d.getTrackingNumber(),
                caller.accountId(), d.getOriginCode(), d.getDestinationCode());
        return view(d, List.of(first));
    }

    private void bookStoreLeg(AuthenticatedAccount caller, CreateDeliveryRequest request, Delivery d) {
        MarketplaceOrderView order;
        try {
            order = orderService.getOrder(request.orderId());
        } catch (OrderServiceException ex) {
            if (ex.getStatus() == 404) {
                throw new DeliveryNotFoundException("Order " + request.orderId() + " not found");
            }
            throw ex;
        }
        boolean seller = Objects.equals(order.sellerAccountId(), caller.accountId());
        boolean buyer = Objects.equals(order.buyerAccountId(), caller.accountId());
        if (!seller && !buyer) {
            throw new DeliveryNotFoundException("Order " + request.orderId() + " not found");
        }
        if (!seller) {
            throw new DeliveryForbiddenException("Only the seller ships a marketplace order; the buyer can track it once booked");
        }
        if (!order.isConfirmed()) {
            throw new DeliveryStateException(order.status(), "Order " + order.orderNumber()
                    + " must be paid (CONFIRMED) before a delivery can be booked; it is " + order.status());
        }
        deliveries.findByOrderExternalIdAndDeliveryType(order.id(), DeliveryType.STORE_TO_CUSTOMER).ifPresent(existing -> {
            throw new DeliveryStateException(existing.getStatus().name(),
                    "A STORE_TO_CUSTOMER delivery already exists for this order: " + existing.getTrackingNumber());
        });
        d.setOrderExternalId(order.id());
        d.setReferenceNumber(order.orderNumber());
        d.setCustomerAccountId(order.buyerAccountId());
        d.setPartnerAccountId(order.sellerAccountId());
    }

    private void checkInbound(RepairRequest repair) {
        checkNotInPerson(repair);
        if (repair.getStatus() != RepairStatus.ACCEPTED) {
            throw new DeliveryStateException(repair.getStatus().name(), "The item can be sent in once the repairer has "
                    + "ACCEPTED the request (before inspection); this request is " + repair.getStatus());
        }
        duplicateCheck(repair, DeliveryType.CUSTOMER_TO_REPAIRER);
    }

    private void checkReturn(AuthenticatedAccount caller, RepairRequest repair) {
        if (!Objects.equals(repair.getRepairerProfile().getAccountExternalId(), caller.accountId())) {
            throw new DeliveryForbiddenException("Only the repairer books the return delivery");
        }
        checkNotInPerson(repair);
        boolean allowed = repair.getStatus() == RepairStatus.COMPLETED
                || (RETURN_AFTER_INBOUND.contains(repair.getStatus())
                    && deliveries.findByRepairRequest_IdAndDeliveryType(repair.getId(), DeliveryType.CUSTOMER_TO_REPAIRER)
                        .map(inbound -> inbound.getStatus() == DeliveryStatus.DELIVERED).orElse(false));
        if (!allowed) {
            throw new DeliveryStateException(repair.getStatus().name(), "The item can be returned once the repair is "
                    + "COMPLETED (or after QUOTE_REJECTED / CANCELLED if it was delivered to the workshop); this request is "
                    + repair.getStatus());
        }
        duplicateCheck(repair, DeliveryType.REPAIRER_TO_CUSTOMER);
    }

    private static void checkNotInPerson(RepairRequest repair) {
        if (repair.getDeliveryMode() == DeliveryMode.IN_PERSON) {
            throw new DeliveryStateException(repair.getStatus().name(), "Repair request " + repair.getRequestNumber()
                    + " is IN_PERSON (the customer visits the workshop), so there is no delivery to track");
        }
    }

    private void duplicateCheck(RepairRequest repair, DeliveryType type) {
        deliveries.findByRepairRequest_IdAndDeliveryType(repair.getId(), type).ifPresent(existing -> {
            throw new DeliveryStateException(existing.getStatus().name(),
                    "A " + type + " delivery already exists for this repair request: " + existing.getTrackingNumber());
        });
    }

    private static Optional<DemoLocation> workshopLocation(RepairerProfile workshop) {
        return DemoLocations.nearest(workshop.getLatitude(), workshop.getLongitude(), workshop.getCity());
    }

    private static Optional<DemoLocation> location(String field, String code, Map<String, String> errors) {
        if (code == null || code.isBlank()) {
            return Optional.empty();
        }
        Optional<DemoLocation> found = DemoLocations.find(code);
        if (found.isEmpty()) {
            errors.put(field, "unknown demo location '" + code + "' (see GET /api/tracking/demo-locations)");
        }
        return found;
    }

    private static void setEnds(Delivery d, DemoLocation origin, DemoLocation destination) {
        d.setOriginCode(origin.code());
        d.setOriginLabel(origin.label());
        d.setOriginCity(origin.city());
        d.setOriginLatitude(origin.latitude());
        d.setOriginLongitude(origin.longitude());
        d.setDestinationCode(destination.code());
        d.setDestinationLabel(destination.label());
        d.setDestinationCity(destination.city());
        d.setDestinationLatitude(destination.latitude());
        d.setDestinationLongitude(destination.longitude());
    }

    private String uniqueTrackingNumber() {
        for (int attempt = 0; attempt < 5; attempt++) {
            String candidate = trackingNumbers.next();
            if (!deliveries.existsByTrackingNumber(candidate)) {
                return candidate;
            }
        }
        throw new IllegalStateException("Could not generate a unique tracking number");
    }

    /* ───────────────────────────── reading ───────────────────────────── */

    @Transactional(readOnly = true)
    public DeliveryResponse get(AuthenticatedAccount caller, String trackingNumber) {
        Delivery d = visible(caller, trackingNumber);
        return view(d, points.findByDelivery_IdOrderBySequenceNoAsc(d.getId()));
    }

    @Transactional(readOnly = true)
    public List<TrackingPointResponse> history(AuthenticatedAccount caller, String trackingNumber) {
        Delivery d = visible(caller, trackingNumber);
        return points.findByDelivery_IdOrderBySequenceNoAsc(d.getId()).stream().map(DeliveryTrackingService::point).toList();
    }

    @Transactional(readOnly = true)
    public List<DeliverySummaryResponse> mine(AuthenticatedAccount caller) {
        return deliveries.findForParty(caller.accountId()).stream().map(DeliveryTrackingService::summary).toList();
    }

    /** Legs of a repair request; 404 unless the caller is its customer or the assigned repairer. */
    @Transactional(readOnly = true)
    public List<DeliverySummaryResponse> forRepairRequest(AuthenticatedAccount caller, Long repairRequestId) {
        RepairRequest repair = visibleRepair(caller, repairRequestId);
        return deliveries.findByRepairRequest_IdOrderByIdAsc(repair.getId()).stream()
                .map(DeliveryTrackingService::summary).toList();
    }

    /** Legs of a marketplace order that the caller is a party of (empty for anyone else). */
    @Transactional(readOnly = true)
    public List<DeliverySummaryResponse> forOrder(AuthenticatedAccount caller, Long orderId) {
        return deliveries.findByOrderExternalIdOrderByIdAsc(orderId).stream()
                .filter(d -> d.isParty(caller.accountId()))
                .map(DeliveryTrackingService::summary).toList();
    }

    /* ───────────────────────────── demo advance ───────────────────────────── */

    /** Moves the simulation one checkpoint forward; 409 once DELIVERED. Either party may advance. */
    @Transactional
    public DeliveryResponse advance(AuthenticatedAccount caller, String trackingNumber) {
        Delivery d = visible(caller, trackingNumber);
        if (d.getStatus().isTerminal()) {
            throw new DeliveryStateException(d.getStatus().name(),
                    "Delivery " + d.getTrackingNumber() + " is already DELIVERED; the simulation has finished");
        }
        DeliveryLocationPoint point = simulator.advance(d, LocalDateTime.now(), caller.accountId());
        deliveries.saveAndFlush(d);
        points.save(point);
        return view(d, points.findByDelivery_IdOrderBySequenceNoAsc(d.getId()));
    }

    /* ───────────────────────────── helpers ───────────────────────────── */

    private Delivery visible(AuthenticatedAccount caller, String trackingNumber) {
        return deliveries.findByTrackingNumber(trackingNumber == null ? "" : trackingNumber.trim())
                .filter(d -> d.isParty(caller.accountId()))
                .orElseThrow(() -> new DeliveryNotFoundException("Delivery " + trackingNumber + " not found"));
    }

    private RepairRequest visibleRepair(AuthenticatedAccount caller, Long id) {
        return requests.findById(id)
                .filter(r -> Objects.equals(r.getCustomerAccountId(), caller.accountId())
                        || (r.getRepairerProfile() != null
                            && Objects.equals(r.getRepairerProfile().getAccountExternalId(), caller.accountId())))
                .orElseThrow(() -> new RepairRequestNotFoundException(id));
    }

    static DeliveryResponse view(Delivery d, List<DeliveryLocationPoint> history) {
        DeliveryStatus next = DeliverySimulator.nextStatus(d.getSimulationStep());
        return new DeliveryResponse(
                true,
                SIMULATION_NOTICE,
                d.getTrackingNumber(),
                d.getDeliveryType().name(),
                d.getDeliveryType().label(),
                CARRIER,
                d.getStatus().name(),
                d.getStatus().label(),
                STATUS_FLOW,
                next == null ? null : next.name(),
                next != null,
                d.getRepairRequest() == null ? null : d.getRepairRequest().getId(),
                d.getOrderExternalId(),
                d.getReferenceNumber(),
                d.getCustomerAccountId(),
                d.getPartnerAccountId(),
                new DeliveryLocationResponse(d.getOriginCode(), d.getOriginLabel(), d.getOriginCity(),
                        d.getOriginLatitude(), d.getOriginLongitude()),
                new DeliveryLocationResponse(d.getDestinationCode(), d.getDestinationLabel(), d.getDestinationCity(),
                        d.getDestinationLatitude(), d.getDestinationLongitude()),
                new DeliveryResponse.Position(d.getCurrentLatitude(), d.getCurrentLongitude()),
                d.getProgressPercent(),
                d.getRouteDistanceKm(),
                DeliverySimulator.remainingKm(d.getRouteDistanceKm(), d.getProgressPercent()),
                d.getEstimatedArrivalAt(),
                d.getCreatedAt(),
                d.getPickedUpAt(),
                d.getDeliveredAt(),
                d.getLastAdvancedAt(),
                List.of(new double[] {d.getOriginLatitude(), d.getOriginLongitude()},
                        new double[] {d.getDestinationLatitude(), d.getDestinationLongitude()}),
                history.stream().map(DeliveryTrackingService::point).toList());
    }

    private static TrackingPointResponse point(DeliveryLocationPoint p) {
        return new TrackingPointResponse(p.getSequenceNo(), p.getStatus().name(), p.getLatitude(), p.getLongitude(),
                p.getProgressPercent(), p.getRemainingKm(), p.getNote(), p.getRecordedAt());
    }

    private static DeliverySummaryResponse summary(Delivery d) {
        return new DeliverySummaryResponse(true, d.getTrackingNumber(), d.getDeliveryType().name(), d.getStatus().name(),
                d.getRepairRequest() == null ? null : d.getRepairRequest().getId(), d.getOrderExternalId(),
                d.getReferenceNumber(), d.getOriginLabel(), d.getOriginCity(), d.getDestinationLabel(),
                d.getDestinationCity(), d.getProgressPercent(), d.getEstimatedArrivalAt(), d.getLastAdvancedAt());
    }
}
